/* ---------- additional operations ---------- */
const DELIVERY_FEE = 49;
const FREE_DELIVERY_ABOVE = 500;
const GST_RATE = 0.05;

/** Server-side price quote. Never trust client totals. */
function quoteCart(userId: string, couponCode?: string) {
  const cart = getCart(userId);
  const db = loadDB();
  let subtotal = 0;
  const lines: Array<{ item_id: string; product_id: string; name: string; quantity: number; unit_price: number; line_total: number; in_stock: boolean; available: number; cod_available: boolean }> = [];
  for (const ci of cart.items) {
    const p = db.products.find(x => x.id === ci.product_id);
    const active = !!p && p.status === 'active';
    const available = p ? p.stock : 0;
    const unit = p ? p.price : ci.price_at_time;
    subtotal += unit * ci.quantity;
    lines.push({ item_id: ci.id, product_id: ci.product_id, name: p?.name || 'Unavailable product', quantity: ci.quantity, unit_price: unit, line_total: unit * ci.quantity, in_stock: active && available >= ci.quantity, available, cod_available: !!p?.cod_available });
  }
  let discount = 0;
  let couponError: string | undefined;
  let couponApplied: string | undefined;
  if (couponCode) {
    const c = db.coupons.find(x => x.code.toLowerCase() === couponCode.trim().toLowerCase() && x.is_active);
    const now = new Date();
    if (!c) couponError = 'Invalid coupon code';
    else if (now < new Date(c.valid_from) || now > new Date(c.valid_until)) couponError = 'This coupon has expired';
    else if (c.usage_limit != null && c.times_used >= c.usage_limit) couponError = 'This coupon has reached its usage limit';
    else if (subtotal < c.min_order_value) couponError = `Minimum order of ₹${c.min_order_value} required`;
    else {
      discount = c.discount_type === 'percentage' ? Math.min((subtotal * c.discount_value) / 100, c.max_discount ?? Infinity) : c.discount_value;
      discount = Math.min(discount, subtotal);
      couponApplied = c.code;
    }
  }
  discount = Math.round(discount * 100) / 100;
  const delivery_charge = subtotal === 0 || subtotal - discount >= FREE_DELIVERY_ABOVE ? 0 : DELIVERY_FEE;
  const tax = Math.round((subtotal - discount) * GST_RATE * 100) / 100;
  const total = Math.round((subtotal - discount + delivery_charge + tax) * 100) / 100;
  return { lines, subtotal, discount, delivery_charge, tax, total, coupon_applied: couponApplied, coupon_error: couponError };
}

