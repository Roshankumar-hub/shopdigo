function nowISO() { return new Date().toISOString(); }

const SCHEMA_VERSION = 3;

/**
 * One-time data migration for databases created by earlier builds. Removes artwork and
 * reviews that were generated by the sample seeder (never real customer or seller data),
 * then recomputes product ratings from the reviews that remain.
 */
/** True when the stored file predates the current schema (a backup is taken before migrating). */
function needsMigration(db: DB): boolean { return (db.schema_version ?? 1) < SCHEMA_VERSION; }

/**
 * Removes the sample catalogue inserted by earlier builds. Genuine records are never matched:
 * products are matched by their exact sample slugs, sellers by sample store name AND no products or orders,
 * and a sample product that already appears on an order is archived instead of deleted so order history stays intact.
 */
function migrateSampleCatalogue(db: DB) {
  const orderedProductIds = new Set((db.order_items || []).map((oi: any) => oi.product_id));
  const removeIds = new Set<string>();
  for (const p of db.products || []) {
    if (!SAMPLE_PRODUCT_SLUGS.has(p.slug)) continue;
    if (orderedProductIds.has(p.id)) { p.status = 'archived_sample'; p.is_featured = false; p.is_trending = false; }
    else removeIds.add(p.id);
  }
  db.products = (db.products || []).filter((p: any) => !removeIds.has(p.id));
  for (const key of ['product_images', 'product_variants', 'reviews', 'questions', 'wishlist', 'cart_items']) {
    (db as any)[key] = ((db as any)[key] || []).filter((r: { product_id: string }) => !removeIds.has(r.product_id));
  }
  const sellerIdsWithProducts = new Set((db.products || []).map((p: any) => p.seller_id));
  const sellerIdsWithOrders = new Set((db.order_items || []).map((oi: any) => oi.seller_id));
  const droppedSellerUserIds = new Set<string>();
  db.sellers = (db.sellers || []).filter((s: any) => {
    const drop = SAMPLE_SELLER_STORES.has(s.store_name) && !sellerIdsWithProducts.has(s.id) && !sellerIdsWithOrders.has(s.id);
    if (drop) droppedSellerUserIds.add(s.user_id);
    return !drop;
  });
  for (const u of db.users || []) if (droppedSellerUserIds.has(u.id) && u.role === 'seller') u.role = 'customer';
  db.pincodes = (db.pincodes || []).filter((x: any) => !SAMPLE_PINCODES.has(x.pincode));
  db.coupons = (db.coupons || []).filter((c: any) => !(SAMPLE_COUPON_CODES.has(c.code) && (c.times_used || 0) === 0));
  db.banners = (db.banners || []).filter((b: any) => !SAMPLE_BANNER_TITLES.has(b.title));
  db.brands = (db.brands || []).filter((b: any) => !(SAMPLE_BRANDS.has(b.name) && !(db.products || []).some((p: any) => p.brand_id === b.id)));
}

function migrateDB(db: DB): boolean {
  if (!needsMigration(db)) return false;
  if ((db.schema_version ?? 1) < 3) migrateSampleCatalogue(db);
  const isGeneratedArt = (u?: string) => typeof u === 'string' && u.startsWith('data:image/svg+xml');
  db.product_images = (db.product_images || []).filter((i: ProductImage) => !isGeneratedArt(i.url));
  const SEED_REVIEWERS = new Set(['Arjun S.', 'Priya P.']); // display names used only by the sample seeder
  db.reviews = (db.reviews || []).filter((r: Review) => !SEED_REVIEWERS.has(r.user_name || ''));
  db.questions = (db.questions || []).filter((q: ProductQuestion) => !(q.user_name === 'Arjun S.' && q.answered_by_seller));
  for (const c of db.categories || []) if (isGeneratedArt(c.image)) c.image = '';
  // Replace the first-release banner copy, which contained discount claims that were not real offers.
  const OLD_BANNER_TITLES = new Set(['Big Billion Days Sale', 'Mega Electronics Sale', 'Fashion Fiesta']);
  const NEW_BANNERS: Record<string, { title: string; subtitle: string; link_url: string }> = {
    'Big Billion Days Sale': { title: 'Shop electronics', subtitle: 'Phones, laptops and audio from sample sellers', link_url: '/search?category=electronics' },
    'Mega Electronics Sale': { title: 'Shop electronics', subtitle: 'Phones, laptops and audio from sample sellers', link_url: '/search?category=electronics' },
    'Fashion Fiesta': { title: 'Fashion for everyday', subtitle: 'Clothing and footwear from sample sellers', link_url: '/search?category=fashion' },
  };
  for (const b of db.banners || []) {
    if (isGeneratedArt(b.image)) b.image = '';
    if (OLD_BANNER_TITLES.has(b.title)) Object.assign(b, NEW_BANNERS[b.title]);
  }
  for (const p of db.products || []) {
    const reviews = (db.reviews as Review[]).filter(r => r.product_id === p.id);
    p.review_count = reviews.length;
    p.rating = reviews.length ? Math.round((reviews.reduce((s, r) => s + r.rating, 0) / reviews.length) * 100) / 100 : 0;
  }
  db.schema_version = SCHEMA_VERSION;
  return true;
}

function loadDB(): DB {
  try {
    if (fs.existsSync(/*turbopackIgnore: true*/ DB_FILE)) {
      const db = JSON.parse(fs.readFileSync(/*turbopackIgnore: true*/ DB_FILE, 'utf8')) as DB;
      if (needsMigration(db)) {
        // Keep an untouched copy of the file before any migration rewrites it.
        const backup = DB_FILE.replace(/\.json$/, `.before-schema-v${SCHEMA_VERSION}.json`);
        if (!fs.existsSync(/*turbopackIgnore: true*/ backup)) fs.copyFileSync(/*turbopackIgnore: true*/ DB_FILE, /*turbopackIgnore: true*/ backup);
        if (migrateDB(db)) saveDB(db);
      }
      return db;
    }
  } catch { /* fall through to reseed */ }
  const seeded = seedData() as DB;
  seeded.sessions = {};
  seeded.schema_version = SCHEMA_VERSION;
  saveDB(seeded);
  return seeded;
}

function saveDB(db: DB) {
  fs.mkdirSync(/*turbopackIgnore: true*/ path.dirname(DB_FILE), { recursive: true });
  const tmp = DB_FILE + '.tmp';
  fs.writeFileSync(/*turbopackIgnore: true*/ tmp, JSON.stringify(db));
  fs.renameSync(/*turbopackIgnore: true*/ tmp, DB_FILE);
}

function resetDB() {
  if (fs.existsSync(/*turbopackIgnore: true*/ DB_FILE)) fs.unlinkSync(/*turbopackIgnore: true*/ DB_FILE);
}

/* ---------- auth ---------- */
const SESSION_TTL_MS = 7 * 24 * 3600 * 1000;

function hashPassword(pw: string): string {
  return bcrypt.hashSync(pw, 10);
}

function registerUser(input: { name: string; email: string; password: string; phone?: string }) {
  const db = loadDB();
  const emailLower = input.email.toLowerCase();
  if (db.users.some(u => u.email.toLowerCase() === emailLower)) throw new Error('An account with this email already exists');
  const id = uuid();
  db.users.push({ id, name: input.name, email: emailLower, phone: input.phone, password_hash: hashPassword(input.password), role: 'customer', created_at: nowISO() });
  db.carts.push({ id: uuid(), user_id: id, items: [], created_at: nowISO(), updated_at: nowISO() });
  saveDB(db);
  return getUserById(id)!;
}

function verifyLogin(email: string, password: string) {
  const db = loadDB();
  const u = db.users.find(u => u.email.toLowerCase() === email.toLowerCase());
  // constant-ish timing: always run a compare
  const hash = u ? u.password_hash : '$2a$10$abcdefghijklmnopqrstuuJ8e9Qq0Yc9YK3nFwE9LrQ0pQx0vLwGe';
  const ok = bcrypt.compareSync(password, hash);
  if (!u || !ok) return null;
  return getUserById(u.id);
}

function createSession(userId: string): string {
  const db = loadDB();
  const token = uuid() + uuid().replace(/-/g, '');
  // purge expired sessions
  for (const [t, s] of Object.entries(db.sessions)) if (new Date(s.expires_at) < new Date()) delete db.sessions[t];
  db.sessions[token] = { user_id: userId, expires_at: new Date(Date.now() + SESSION_TTL_MS).toISOString() };
  saveDB(db);
  return token;
}

function destroySession(token: string) {
  const db = loadDB();
  delete db.sessions[token];
  saveDB(db);
}

function getUserBySession(token: string | undefined | null) {
  if (!token) return null;
  const db = loadDB();
  const s = db.sessions[token];
  if (!s || new Date(s.expires_at) < new Date()) return null;
  return getUserById(s.user_id);
}

function getUserById(id: string) {
  const db = loadDB();
  const u = db.users.find(u => u.id === id);
  if (!u) return null;
  const seller = db.sellers.find(s => s.user_id === id);
  return {
    id: u.id, name: u.name, email: u.email, phone: u.phone, role: u.role,
    seller_id: seller?.id ?? null, seller_status: seller?.status ?? null,
  };
}

/* ---------- products ---------- */
function listProducts(filter?: { category?: string; brand?: string; seller_id?: string; search?: string; minPrice?: number; maxPrice?: number; minRating?: number; status?: string; featured?: boolean; trending?: boolean; sort?: string }) {
  const db = loadDB();
  let items = db.products.slice();
  if (filter?.status) items = items.filter(p => p.status === filter.status);
  else items = items.filter(p => p.status === 'active');
  if (filter?.category) {
    const key = filter.category.toLowerCase();
    const cats = db.categories.filter(c => c.id === filter.category || c.slug === key || c.name.toLowerCase() === key);
    const ids = new Set<string>();
    for (const c of cats) {
      ids.add(c.id);
      db.categories.filter(x => x.parent_id === c.id).forEach(x => ids.add(x.id));
    }
    items = items.filter(p => ids.has(p.category_id));
  }
  if (filter?.brand) items = items.filter(p => p.brand_id === filter.brand);
  if (filter?.seller_id) items = items.filter(p => p.seller_id === filter.seller_id);
  if (filter?.featured) items = items.filter(p => p.is_featured);
  if (filter?.trending) items = items.filter(p => p.is_trending);
  if (filter?.minPrice != null) items = items.filter(p => p.price >= filter.minPrice!);
  if (filter?.maxPrice != null) items = items.filter(p => p.price <= filter.maxPrice!);
  if (filter?.minRating != null) items = items.filter(p => p.rating >= filter.minRating!);
  if (filter?.search) {
    const s = filter.search.toLowerCase();
    items = items.filter(p => p.name.toLowerCase().includes(s) || p.description.toLowerCase().includes(s) || (p.brand_name||'').toLowerCase().includes(s));
  }
  if (filter?.sort) {
    switch (filter.sort) {
      case 'price_low': items.sort((a,b) => a.price - b.price); break;
      case 'price_high': items.sort((a,b) => b.price - a.price); break;
      case 'newest': items.sort((a,b) => (b.created_at > a.created_at ? 1 : -1)); break;
      case 'discount': items.sort((a,b) => b.discount_percent - a.discount_percent); break;
      case 'rating': items.sort((a,b) => b.rating - a.rating); break;
      case 'popularity': items.sort((a,b) => b.review_count - a.review_count); break;
      default: break;
    }
  }
  return items.map(p => attachProductRelations(p, db));
}

/* ---------- storefront helpers ---------- */
function listProductsByIds(ids: string[]) {
  const db = loadDB();
  const byId = new Map(db.products.map(p => [p.id, p]));
  return ids.map(id => byId.get(id)).filter((p): p is Product => !!p && p.status === 'active').map(p => attachProductRelations(p, db));
}
function listBrandsWithCounts() {
  const db = loadDB();
  return db.brands.map(b => ({ ...b, product_count: db.products.filter(p => p.brand_id === b.id && p.status === 'active').length }))
    .filter(b => b.product_count > 0)
    .sort((a, b) => b.product_count - a.product_count);
}
