/**
 * Marks an order paid. Only call this AFTER server-side verification of the
 * Razorpay signature and a fetch of the payment status from Razorpay's API
 * (or a verified webhook). Idempotent.
 */
function markOrderPaid(orderId: string, paymentId: string) {
  const db = loadDB();
  const order = db.orders.find(o => o.id === orderId);
  if (!order) throw new Error('Order not found');
  if (order.payment_status === 'paid') return getOrderById(orderId);
  if (order.status === 'cancelled') throw new Error('Order was cancelled before payment');
  order.payment_status = 'paid';
  order.razorpay_payment_id = paymentId;
  order.status = 'confirmed';
  order.updated_at = nowISO();
  for (const oi of db.order_items.filter(x => x.order_id === orderId)) {
    const gross = oi.price * oi.quantity;
    const seller = db.sellers.find(s => s.id === oi.seller_id)!;
    const commission = Math.round(gross * (seller.commission_rate / 100) * 100) / 100;
    db.ledger.push({ id: uuid(), seller_id: oi.seller_id, order_id: orderId, order_item_id: oi.id, type: 'sale', amount: gross, description: `Sale: order ${order.order_number}`, created_at: nowISO() });
    db.ledger.push({ id: uuid(), seller_id: oi.seller_id, order_id: orderId, order_item_id: oi.id, type: 'commission', amount: -commission, description: `Marketplace commission (${seller.commission_rate}%)`, created_at: nowISO() });
  }
  db.notifications.push({ id: uuid(), is_read: false, user_id: order.user_id, title: 'Payment successful', message: `Payment received for order ${order.order_number}.`, type: 'payment', link_url: `/account/orders/${order.id}`, created_at: nowISO() });
  saveDB(db);
  return getOrderById(orderId);
}

