/* ---------- cart ---------- */
function getCart(userId: string): Cart {
  const db = loadDB();
  let cart = db.carts.find(c => c.user_id === userId);
  if (!cart) {
    cart = { id: uuid(), user_id: userId, items: [], created_at: nowISO(), updated_at: nowISO() };
    db.carts.push(cart);
    saveDB(db);
  }
  const items = db.cart_items.filter(ci => ci.cart_id === cart!.id).map(ci => ({ ...ci, product: getProductById(ci.product_id) || undefined }));
  return { ...cart, items };
}

function addToCart(userId: string, productId: string, quantity: number, variantId?: string) {
  const db = loadDB();
  const cart = db.carts.find(c => c.user_id === userId)!;
  const product = db.products.find(p => p.id === productId);
  if (!product || product.status !== 'active') throw new Error('Product not found');
  if (variantId) {
    const variant = db.product_variants.find(v => v.id === variantId && v.product_id === productId);
    if (!variant) throw new Error('Selected size is not available for this product');
    if (variant.stock < quantity) throw new Error('Not enough stock available for the selected size');
  } else if (product.stock < quantity) throw new Error('Not enough stock available');
  const existing = db.cart_items.find(ci => ci.cart_id === cart.id && ci.product_id === productId && ci.variant_id === variantId);
  if (existing) {
    const available = variantId ? (db.product_variants.find(v => v.id === variantId)?.stock ?? 0) : product.stock;
    if (available < existing.quantity + quantity) throw new Error('Not enough stock available');
    existing.quantity += quantity;
  } else {
    db.cart_items.push({ id: uuid(), cart_id: cart.id, product_id: productId, variant_id: variantId, quantity, price_at_time: product.price, created_at: nowISO() });
  }
  cart.updated_at = nowISO();
  saveDB(db);
  return getCart(userId);
}

function updateCartItem(userId: string, itemId: string, quantity: number) {
  const db = loadDB();
  const cart = db.carts.find(c => c.user_id === userId)!;
  const item = db.cart_items.find(ci => ci.id === itemId && ci.cart_id === cart.id);
  if (!item) throw new Error('Item not found');
  const product = db.products.find(p => p.id === item.product_id);
  if (product && quantity > product.stock) throw new Error(`Only ${product.stock} items available`);
  if (quantity <= 0) {
    db.cart_items = db.cart_items.filter(ci => ci.id !== itemId);
  } else {
    item.quantity = quantity;
  }
  saveDB(db);
  return getCart(userId);
}

function removeFromCart(userId: string, itemId: string) {
  const db = loadDB();
  const cart = db.carts.find(c => c.user_id === userId)!;
  db.cart_items = db.cart_items.filter(ci => !(ci.id === itemId && ci.cart_id === cart.id));
  saveDB(db);
  return getCart(userId);
}

function clearCart(userId: string) {
  const db = loadDB();
  const cart = db.carts.find(c => c.user_id === userId)!;
  db.cart_items = db.cart_items.filter(ci => ci.cart_id !== cart.id);
  saveDB(db);
}

