function getSellerLedgerSummary(sellerId: string) {
  const ledger = getSellerLedger(sellerId);
  const sum = (t: string) => ledger.filter(l => l.type === t).reduce((s, l) => s + l.amount, 0);
  return { gross_sales: sum('sale'), commission: sum('commission'), refunds: sum('refund'), adjustments: sum('adjustment'), payouts: sum('payout'), net_payable: ledger.reduce((s, l) => s + l.amount, 0) };
}

