function getProductBySlug(slug: string) {
  const db = loadDB();
  const p = db.products.find(p => p.slug === slug && p.status !== 'archived_sample');
  return p ? attachProductRelations(p, db) : null;
}
function getProductById(id: string) {
  const db = loadDB();
  const p = db.products.find(p => p.id === id);
  return p ? attachProductRelations(p, db) : null;
}

function attachProductRelations(p: Product, db: DB): Product {
  const images = db.product_images.filter(i => i.product_id === p.id).sort((a,b)=>a.position-b.position);
  const variants = db.product_variants.filter(v => v.product_id === p.id);
  const cat = db.categories.find(c => c.id === p.category_id);
  const brand = db.brands.find(b => b.id === p.brand_id);
  const seller = db.sellers.find(s => s.id === p.seller_id);
  return { ...p, images, variants, category_name: cat?.name, brand_name: brand?.name, seller_name: seller?.store_name };
}

function createProduct(data: Omit<Product, 'id'|'rating'|'review_count'|'created_at'|'updated_at'|'images'|'variants'> & { images?: string[]; variants?: ProductVariant[] }): Product {
  const db = loadDB();
  const id = uuid();
  const product: Product = {
    id,
    seller_id: data.seller_id, category_id: data.category_id, brand_id: data.brand_id,
    name: data.name, slug: data.slug, description: data.description, specifications: data.specifications || {},
    mrp: data.mrp, price: data.price, discount_percent: data.discount_percent || Math.round(((data.mrp - data.price) / data.mrp) * 100),
    stock: data.stock, rating: 0, review_count: 0,
    status: data.status || 'pending_approval', is_featured: false, is_trending: false,
    cod_available: data.cod_available ?? true, delivery_days: data.delivery_days || 5, return_window_days: data.return_window_days || 7,
    images: [], variants: [], created_at: nowISO(), updated_at: nowISO(),
  };
  db.products.push(product);
  (data.images || []).forEach((url, i) => {
    const img: ProductImage = { id: uuid(), product_id: id, url, position: i };
    db.product_images.push(img);
  });
  (data.variants || []).forEach(v => db.product_variants.push({ ...v, id: uuid(), product_id: id }));
  saveDB(db);
  return attachProductRelations(product, db);
}

function updateProduct(id: string, patch: Partial<Product>) {
  const db = loadDB();
  const idx = db.products.findIndex(p => p.id === id);
  if (idx === -1) throw new Error('Product not found');
  db.products[idx] = { ...db.products[idx], ...patch, updated_at: nowISO() };
  saveDB(db);
  return attachProductRelations(db.products[idx], db);
}

