/* ---------- orders ---------- */
function generateOrderNumber(db: DB) {
  const n = db.orders.length + 1;
  return 'SD' + Date.now().toString().slice(-7) + String(n).padStart(3, '0');
}

function createOrder(input: { userId: string; addressId: string; paymentMethod: 'razorpay'|'cod'; couponCode?: string; notes?: string; idempotencyKey: string; }): Order {
  const cart = getCart(input.userId);
  const db = loadDB();
  const existing = db.orders.find(o => o.user_id === input.userId && o.idempotency_key === input.idempotencyKey);
  if (existing) return getOrderById(existing.id)!;
  if (cart.items.length === 0) throw new Error('Cart is empty');
  // Single pricing path: server-side quote (never trust client totals).
  const quote = quoteCart(input.userId, input.couponCode);
  if (quote.lines.length === 0) throw new Error('Cart is empty');
  if (input.couponCode && quote.coupon_error) throw new Error(quote.coupon_error);
  const unavailable = quote.lines.find(l => !l.in_stock);
  if (unavailable) throw new Error(`"${unavailable.name}" is out of stock or unavailable in the requested quantity. Please update your cart.`);
  if (input.paymentMethod === 'cod' && quote.lines.some(l => !l.cod_available)) throw new Error('Cash on Delivery is not available for one or more items');
  const orderItemsData = quote.lines.map(l => {
    const product = db.products.find(p => p.id === l.product_id)!;
    const ci = cart.items.find(c => c.id === l.item_id)!;
    return { product, quantity: l.quantity, price: product.price, mrp: product.mrp, seller_id: product.seller_id, variant_id: ci.variant_id };
  });
  const subtotal = quote.subtotal, discount = quote.discount, delivery_charge = quote.delivery_charge, tax = quote.tax, total = quote.total;
  if (quote.coupon_applied) {
    const c = db.coupons.find(x => x.code === quote.coupon_applied)!;
    c.times_used += 1;
  }

  const orderId = uuid();
  const order: Order = {
    id: orderId,
    order_number: generateOrderNumber(db),
    user_id: input.userId,
    address_id: input.addressId,
    items: [],
    subtotal, discount, delivery_charge, tax, total,
    coupon_code: quote.coupon_applied,
    payment_method: input.paymentMethod,
    payment_status: input.paymentMethod === 'cod' ? 'pending' : 'pending',
    idempotency_key: input.idempotencyKey,
    status: 'placed',
    notes: input.notes,
    created_at: nowISO(), updated_at: nowISO(),
  };

  for (const oi of orderItemsData) {
    const orderItemId = uuid();
    const orderItem: OrderItem = {
      id: orderItemId, order_id: orderId, product_id: oi.product.id, seller_id: oi.seller_id,
      variant_id: oi.variant_id, quantity: oi.quantity, price: oi.price, mrp: oi.mrp, status: 'placed',
      created_at: nowISO(),
    };
    db.order_items.push(orderItem);
    db.order_status_history.push({ id: uuid(), order_item_id: orderItemId, status: 'placed', note: 'Order placed', created_at: nowISO() });
    // decrement stock
    const p = db.products.find(x => x.id === oi.product.id)!;
    p.stock -= oi.quantity;
    p.updated_at = nowISO();
    if (oi.variant_id) { const v = db.product_variants.find(x => x.id === oi.variant_id); if (v) v.stock -= oi.quantity; }
  }
  db.orders.push(order);

  // Clear cart
  db.cart_items = db.cart_items.filter(ci => ci.cart_id !== cart.id);

  // Notifications
  db.notifications.push({ id: uuid(), is_read: false, user_id: input.userId, title: 'Order placed', message: `Your order ${order.order_number} has been placed successfully.`, type: 'order', link_url: `/account/orders/${order.id}`, created_at: nowISO() });

  saveDB(db);
  return getOrderById(order.id)!;
}

