function toggleWishlist(userId: string, productId: string): boolean {
  const db = loadDB();
  const existing = db.wishlist.find(w => w.user_id === userId && w.product_id === productId);
  if (existing) db.wishlist = db.wishlist.filter(w => w.id !== existing.id);
  else db.wishlist.push({ id: uuid(), user_id: userId, product_id: productId, created_at: nowISO() });
  saveDB(db);
  return !existing;
}

