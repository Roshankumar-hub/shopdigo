'use client';

import Link from 'next/link';
import { cn } from '@/lib/utils';
import { LAYOUT, PALETTE, TAGLINE, WORDMARK } from './brand/geometry';
import { MarkArt, useMarkIds } from './brand/MarkArt';

interface LogoProps {
  size?: 'sm' | 'md' | 'lg';
  /** Stacked lockup with the tagline. Otherwise the horizontal lockup. */
  withTagline?: boolean;
  /** Light wordmark for dark backgrounds. */
  onDark?: boolean;
  /** Tags the parts so globals.css can run the loader reveal. */
  animated?: boolean;
  /** Links to the homepage. Set false where the logo is decorative (loader). */
  asLink?: boolean;
  className?: string;
}

const HORIZONTAL_HEIGHT = { sm: 'h-9', md: 'h-11', lg: 'h-14' } as const;
const STACKED_WIDTH = { sm: 'w-40', md: 'w-52', lg: 'w-64' } as const;

/**
 * SHOPDIGO logo. One approved asset is used everywhere; the geometry is generated by tools/build_logo.py.
 */
export default function Logo({
  size = 'md',
  withTagline = false,
  onDark = false,
  animated = false,
  asLink = true,
  className,
}: LogoProps) {
  const ids = useMarkIds();
  const stacked = withTagline;
  const L = stacked ? LAYOUT.stacked : LAYOUT.horizontal;
  const shopFill = onDark ? '#FFFFFF' : PALETTE.navy;
  const digoFill = onDark ? '#60A5FA' : PALETTE.blue;
  const tagFill = onDark ? '#E2E8F0' : PALETTE.navy;
  const sizeClass = stacked ? STACKED_WIDTH[size] : HORIZONTAL_HEIGHT[size];

  const svg = (
    <svg
      viewBox={`0 0 ${L.width} ${L.height}`}
      role="img"
      aria-label={stacked ? 'SHOPDIGO – Shop more, live better' : 'SHOPDIGO'}
      className={cn('block h-auto max-w-full overflow-visible', sizeClass)}
    >
      <g transform={`translate(${L.markX} ${L.markY}) scale(${L.markScale})`} className={animated ? 'sd-mark' : undefined}>
        <MarkArt ids={ids} />
      </g>
      <g
        transform={
          stacked
            ? `translate(${L.wordX} ${L.wordBaseline})`
            : `translate(${L.wordX} ${L.wordBaseline}) scale(${(L as { wordScale: number }).wordScale})`
        }
        className={animated ? 'sd-word' : undefined}
      >
        <path d={WORDMARK.shop} fill={shopFill} stroke={shopFill} strokeWidth={WORDMARK.stroke} strokeLinejoin="round" />
        <path
          d={WORDMARK.digo}
          fill={digoFill}
          stroke={digoFill}
          strokeWidth={WORDMARK.stroke}
          strokeLinejoin="round"
          className={animated ? 'sd-digo' : undefined}
        />
      </g>
      {stacked && (
        <g transform={`translate(${(L as { tagX: number }).tagX} ${(L as { tagBaseline: number }).tagBaseline})`} className={animated ? 'sd-tag' : undefined} fill={tagFill}>
          <path d={TAGLINE.left} />
          <path d={TAGLINE.right} />
          <circle cx={TAGLINE.dot.cx} cy={TAGLINE.dot.cy} r={TAGLINE.dot.r} fill={PALETTE.yellow} className={animated ? 'sd-dot' : undefined} />
        </g>
      )}
    </svg>
  );

  if (!asLink) return <div className={cn('inline-flex', className)}>{svg}</div>;
  return (
    <Link href="/" className={cn('inline-flex items-center', className)} aria-label="SHOPDIGO home">
      {svg}
    </Link>
  );
}

